#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
HUFLIT reproducibility data builder
===================================

Purpose
-------
Build the exact five evaluation conditions described in the revised HUFLIT
manuscript using ONE shared cross-document distractor pool derived from the
training split and reused for noisy train / validation / test construction.

This script is intentionally narrower than the older generic databuildt.py:
- one shared training-derived distractor pool;
- clean / query-aligned / query-distant noisy construction;
- additive and substitutive test conditions;
- unique clean-matched control data;
- deterministic seed;
- manifest + per-row provenance at chunk level.

Important
---------
This script aligns the *builder behavior* with the revised manuscript.
It does not prove that previously reported Tables 4-8 were generated by this
exact implementation. If the old run used a different distractor-pool variant,
rerun the experiment or revise the manuscript accordingly.

Expected repository helpers
---------------------------
src/
  retrieval_tokenizer.py
  rulebase_chunkforpdf.py

Expected source data
--------------------
A HuggingFace Dataset/DatasetDict saved with `datasets.save_to_disk`, containing
train / validation / test splits with article and abstract fields.

Example
-------
python src/databuild_huflit_shared_pool.py \
  --arxiv_dir ./dataset/arxiv \
  --output_dir ./prepared_data_huflit \
  --train_limit 20000 \
  --valid_limit 1000 \
  --test_limit 500 \
  --noise_pool_offset 20000 \
  --noise_pool_limit 10000 \
  --seed 42
"""

from __future__ import annotations

import argparse
import json
import random
import re
from dataclasses import dataclass
from pathlib import Path
from typing import Any, Dict, Iterable, List, Optional, Sequence, Tuple

import numpy as np
from datasets import DatasetDict, load_from_disk

from retrieval_tokenizer import DenseEncoder, Document
from rulebase_chunkforpdf import process_document


QUERY_TEMPLATES = [
    "Summarize the main contribution of this paper",
    "Summarize the proposed method and main findings of this paper",
    "What problem does this paper address and how does it solve it?",
]

DEFAULT_EMBEDDER = "sentence-transformers/all-MiniLM-L6-v2"

# Manuscript-aligned similarity bands
QUERY_ALIGNED_LOW = 70
QUERY_ALIGNED_HIGH = 95
QUERY_ALIGNED_FALLBACK_LOW = 60
QUERY_ALIGNED_FALLBACK_HIGH = 98

QUERY_DISTANT_MAX = 10
QUERY_DISTANT_FALLBACK_MAX = 20


@dataclass
class EncodedPaper:
    paper_id: str
    article: str
    abstract: str
    chunks: List[Dict[str, Any]]
    documents: List[Document]
    embeddings: np.ndarray


def parse_args() -> argparse.Namespace:
    p = argparse.ArgumentParser(
        description=(
            "Build HUFLIT proof-of-concept RAG summarization data with one "
            "shared training-derived distractor pool."
        )
    )
    p.add_argument("--arxiv_dir", type=str, required=True)
    p.add_argument("--output_dir", type=str, required=True)

    p.add_argument("--train_limit", type=int, default=20000)
    p.add_argument("--valid_limit", type=int, default=1000)
    p.add_argument("--test_limit", type=int, default=500)

    # The shared pool is derived only from the TRAIN split.
    p.add_argument(
        "--noise_pool_offset",
        type=int,
        default=20000,
        help="Start index in filtered TRAIN split for the shared distractor pool.",
    )
    p.add_argument("--noise_pool_limit", type=int, default=10000)

    p.add_argument("--final_k", type=int, default=3)
    p.add_argument("--noise_k", type=int, default=2)
    p.add_argument("--substitutive_clean_k", type=int, default=1)
    p.add_argument("--min_chunks", type=int, default=3)

    p.add_argument("--min_target_words", type=int, default=20)
    p.add_argument("--max_target_words", type=int, default=512)

    p.add_argument("--embedder", type=str, default=DEFAULT_EMBEDDER)
    p.add_argument("--encode_batch_size", type=int, default=32)
    p.add_argument("--encoder_max_length", type=int, default=512)
    p.add_argument("--device", type=str, default=None)

    p.add_argument("--mmr_lambda", type=float, default=0.5)
    p.add_argument("--seed", type=int, default=42)

    p.add_argument(
        "--single_query",
        action="store_true",
        help="Always use the first query template instead of deterministic per-paper selection.",
    )
    p.add_argument(
        "--no_shuffle_noisy",
        action="store_true",
        help="Disable post-merge shuffling of target/noise chunks.",
    )
    return p.parse_args()


def normalize_text(x: Any) -> str:
    if x is None:
        return ""
    if isinstance(x, list):
        return " ".join(str(v).strip() for v in x if str(v).strip())
    return str(x).replace("\\n", "\n").replace("/n", "\n").strip()


def word_count(text: str) -> int:
    return len(normalize_text(text).split())


def load_split(root: str, split_name: str) -> List[Dict[str, str]]:
    root_path = Path(root)
    obj = load_from_disk(str(root_path))

    if isinstance(obj, DatasetDict):
        if split_name not in obj:
            raise KeyError(f"Missing split '{split_name}' in {root_path}")
        ds = obj[split_name]
    else:
        # Support root/train, root/validation, root/test saved separately.
        split_path = root_path / split_name
        if split_path.exists():
            ds = load_from_disk(str(split_path))
        else:
            raise ValueError(
                f"{root_path} is not a DatasetDict and {split_path} does not exist."
            )

    rows: List[Dict[str, str]] = []
    for i, sample in enumerate(ds):
        article = normalize_text(sample.get("article", ""))
        abstract = normalize_text(sample.get("abstract", ""))
        if not article or not abstract:
            continue
        rows.append({
            "paper_id": f"{split_name}_{i}",
            "article": article,
            "abstract": abstract,
        })
    return rows


def filter_target_lengths(
    rows: List[Dict[str, str]],
    min_words: int,
    max_words: int,
) -> List[Dict[str, str]]:
    out = []
    for row in rows:
        n = word_count(row["abstract"])
        if min_words <= n <= max_words and row["article"].strip():
            out.append(row)
    return out


def choose_query(paper_id: str, single_query: bool) -> str:
    if single_query:
        return QUERY_TEMPLATES[0]

    # Stable across Python processes; avoid built-in hash randomization.
    h = sum((i + 1) * ord(ch) for i, ch in enumerate(str(paper_id)))
    return QUERY_TEMPLATES[h % len(QUERY_TEMPLATES)]


def make_documents(paper_id: str, chunks: List[Dict[str, Any]]) -> List[Document]:
    docs: List[Document] = []
    for ch in chunks:
        text = normalize_text(ch.get("text", ""))
        if not text:
            continue
        cid = int(ch.get("chunk_id", len(docs)))
        docs.append(
            Document(
                id=f"{paper_id}::chunk_{cid}",
                text=text,
                metadata={
                    "paper_id": paper_id,
                    "source_doc_id": paper_id,
                    "chunk_id": cid,
                    "section": ch.get("section", ""),
                },
            )
        )
    return docs


def encode_paper(
    row: Dict[str, str],
    encoder: DenseEncoder,
    min_chunks: int,
) -> Optional[EncodedPaper]:
    parsed = process_document(row["article"], source_doc_id=row["paper_id"])
    chunks = parsed.get("chunks", [])
    if len(chunks) < min_chunks:
        return None

    docs = make_documents(row["paper_id"], chunks)
    if len(docs) < min_chunks:
        return None

    embs = encoder.encode([d.text for d in docs]).astype(np.float32)
    return EncodedPaper(
        paper_id=row["paper_id"],
        article=row["article"],
        abstract=row["abstract"],
        chunks=chunks,
        documents=docs,
        embeddings=embs,
    )


def encode_rows(
    rows: Sequence[Dict[str, str]],
    encoder: DenseEncoder,
    min_chunks: int,
    label: str,
) -> List[EncodedPaper]:
    encoded: List[EncodedPaper] = []
    total = len(rows)
    for i, row in enumerate(rows, 1):
        try:
            p = encode_paper(row, encoder, min_chunks=min_chunks)
            if p is not None:
                encoded.append(p)
        except Exception as e:
            print(f"[WARN] {label}::{row.get('paper_id')}: {type(e).__name__}: {e}")

        if i % 250 == 0 or i == total:
            print(f"[{label}] {i}/{total} -> valid={len(encoded)}")
    return encoded


def build_shared_noise_pool(
    rows: Sequence[Dict[str, str]],
    encoder: DenseEncoder,
) -> Tuple[List[Document], np.ndarray]:
    """
    Build ONE shared distractor pool from TRAIN-split rows only.
    This same pool is reused for noisy train, validation, and test construction.
    """
    docs: List[Document] = []
    embs: List[np.ndarray] = []

    total = len(rows)
    for i, row in enumerate(rows, 1):
        try:
            parsed = process_document(row["article"], source_doc_id=row["paper_id"])
            row_docs = make_documents(row["paper_id"], parsed.get("chunks", []))
            if not row_docs:
                continue
            row_embs = encoder.encode([d.text for d in row_docs]).astype(np.float32)
            docs.extend(row_docs)
            embs.append(row_embs)
        except Exception as e:
            print(f"[WARN] noise_pool::{row.get('paper_id')}: {type(e).__name__}: {e}")

        if i % 250 == 0 or i == total:
            print(f"[noise_pool] {i}/{total} papers -> chunks={len(docs)}")

    if not docs or not embs:
        raise RuntimeError("Shared noise pool is empty.")

    arr = np.vstack(embs).astype(np.float32)
    if len(docs) != len(arr):
        raise RuntimeError("Noise-pool document/embedding alignment failure.")
    return docs, arr


def mmr_select(
    query_emb: np.ndarray,
    doc_embs: np.ndarray,
    relevance: np.ndarray,
    k: int,
    mmr_lambda: float,
) -> List[int]:
    n = len(doc_embs)
    if n == 0 or k <= 0:
        return []

    k = min(k, n)
    sims = np.asarray(doc_embs @ doc_embs.T, dtype=np.float32)
    selected: List[int] = []
    remaining = set(range(n))

    for _ in range(k):
        best = None
        best_score = -float("inf")
        for pos in remaining:
            redundancy = float(np.max(sims[pos, selected])) if selected else 0.0
            score = mmr_lambda * float(relevance[pos]) - (1.0 - mmr_lambda) * redundancy
            if score > best_score:
                best_score = score
                best = pos
        if best is None:
            break
        selected.append(best)
        remaining.remove(best)
    return selected


def retrieve_target_chunks(
    paper: EncodedPaper,
    query_emb: np.ndarray,
    k: int,
    mmr_lambda: float,
) -> List[Document]:
    qe = query_emb.reshape(1, -1)
    scores = np.asarray((paper.embeddings @ qe.T).squeeze(), dtype=np.float32)
    scores = np.atleast_1d(scores)

    candidate_k = min(max(k * 5, 50), len(scores))
    ranked = np.argsort(-scores)[:candidate_k]
    cand_embs = paper.embeddings[ranked]
    cand_scores = scores[ranked]

    chosen_positions = mmr_select(
        query_emb=qe,
        doc_embs=cand_embs,
        relevance=cand_scores,
        k=k,
        mmr_lambda=mmr_lambda,
    )
    return [paper.documents[int(ranked[p])] for p in chosen_positions]


def source_doc_id(doc: Document) -> str:
    return str(
        doc.metadata.get("source_doc_id")
        or doc.metadata.get("paper_id")
        or str(doc.id).split("::")[0]
    )


def select_noise(
    shared_pool_docs: Sequence[Document],
    shared_pool_embs: np.ndarray,
    query_emb: np.ndarray,
    current_paper_id: str,
    clean_docs: Sequence[Document],
    noise_k: int,
    mode: str,
    rng: random.Random,
) -> List[Document]:
    clean_ids = {d.id for d in clean_docs}

    valid_idx = [
        i
        for i, d in enumerate(shared_pool_docs)
        if d.id not in clean_ids and source_doc_id(d) != current_paper_id
    ]
    if not valid_idx:
        return []

    qe = query_emb.reshape(1, -1)
    cand_embs = shared_pool_embs[valid_idx]
    sims = np.asarray((cand_embs @ qe.T).squeeze(), dtype=np.float32)
    sims = np.atleast_1d(sims)

    if mode == "query_aligned":
        lo = np.percentile(sims, QUERY_ALIGNED_LOW)
        hi = np.percentile(sims, QUERY_ALIGNED_HIGH)
        keep = np.where((sims >= lo) & (sims <= hi))[0]
        if len(keep) < noise_k:
            lo = np.percentile(sims, QUERY_ALIGNED_FALLBACK_LOW)
            hi = np.percentile(sims, QUERY_ALIGNED_FALLBACK_HIGH)
            keep = np.where((sims >= lo) & (sims <= hi))[0]

    elif mode == "query_distant":
        hi = np.percentile(sims, QUERY_DISTANT_MAX)
        keep = np.where(sims <= hi)[0]
        if len(keep) < noise_k:
            hi = np.percentile(sims, QUERY_DISTANT_FALLBACK_MAX)
            keep = np.where(sims <= hi)[0]

    else:
        raise ValueError(f"Unknown noise mode: {mode}")

    if len(keep) < noise_k:
        return []

    choices = rng.sample(keep.tolist(), noise_k)
    return [shared_pool_docs[valid_idx[j]] for j in choices]


def build_input_text(query: str, docs: Sequence[Document]) -> str:
    # Stable, explicit source construction.
    blocks = [f"[QUERY]\n{query}"]
    for i, doc in enumerate(docs, 1):
        blocks.append(f"[CONTEXT {i}]\n{doc.text}")
    return "\n\n".join(blocks)


def make_record(
    paper: EncodedPaper,
    query: str,
    docs: Sequence[Document],
    target_docs: Sequence[Document],
    noise_docs: Sequence[Document],
    split: str,
    condition: str,
) -> Dict[str, Any]:
    target_ids = {d.id for d in target_docs}
    noise_ids = {d.id for d in noise_docs}

    segments = []
    for pos, d in enumerate(docs):
        role = "target" if d.id in target_ids else "noise" if d.id in noise_ids else "unknown"
        segments.append({
            "position": pos,
            "chunk_id": d.id,
            "source_doc_id": source_doc_id(d),
            "role": role,
            "text": d.text,
        })

    return {
        "paper_id": paper.paper_id,
        "split": split,
        "condition": condition,
        "sample_type": "clean" if not noise_docs else "noisy",
        "query": query,
        "input_text": build_input_text(query, docs),
        "target_text": paper.abstract,
        "num_contexts": len(docs),
        "num_target_chunks": len(target_docs),
        "num_noise_chunks": len(noise_docs),
        "context_chunk_ids": [d.id for d in docs],
        "context_source_doc_ids": [source_doc_id(d) for d in docs],
        "target_chunk_ids": [d.id for d in target_docs],
        "noise_chunk_ids": [d.id for d in noise_docs],
        # Chunk-level provenance retained for future instrumented NER/TRR work.
        "context_segments": segments,
    }


def build_conditions_for_paper(
    paper: EncodedPaper,
    encoder: DenseEncoder,
    shared_pool_docs: Sequence[Document],
    shared_pool_embs: np.ndarray,
    final_k: int,
    noise_k: int,
    substitutive_clean_k: int,
    mmr_lambda: float,
    rng: random.Random,
    shuffle_noisy: bool,
    split: str,
    single_query: bool,
) -> Dict[str, Optional[Dict[str, Any]]]:
    query = choose_query(paper.paper_id, single_query=single_query)
    query_emb = encoder.encode(query)[0]

    target = retrieve_target_chunks(
        paper=paper,
        query_emb=query_emb,
        k=final_k,
        mmr_lambda=mmr_lambda,
    )
    if len(target) < final_k:
        return {}

    aligned_noise = select_noise(
        shared_pool_docs, shared_pool_embs, query_emb,
        current_paper_id=paper.paper_id,
        clean_docs=target,
        noise_k=noise_k,
        mode="query_aligned",
        rng=rng,
    )
    distant_noise = select_noise(
        shared_pool_docs, shared_pool_embs, query_emb,
        current_paper_id=paper.paper_id,
        clean_docs=target,
        noise_k=noise_k,
        mode="query_distant",
        rng=rng,
    )

    out: Dict[str, Optional[Dict[str, Any]]] = {}

    # Clean
    out["clean"] = make_record(
        paper, query, target, target, [], split, "clean"
    )

    def noisy_record(
        condition: str,
        target_subset: Sequence[Document],
        noise_subset: Sequence[Document],
    ) -> Optional[Dict[str, Any]]:
        if len(noise_subset) != noise_k:
            return None
        docs = list(target_subset) + list(noise_subset)
        if shuffle_noisy:
            rng.shuffle(docs)
        return make_record(
            paper, query, docs, target_subset, noise_subset, split, condition
        )

    # Additive: 3 target + 2 noise
    out["query_aligned_additive"] = noisy_record(
        "query_aligned_additive", target, aligned_noise
    )
    out["query_distant_additive"] = noisy_record(
        "query_distant_additive", target, distant_noise
    )

    # Substitutive: 1 target + 2 noise = 3 total chunks
    retained_target = target[:substitutive_clean_k]
    out["query_aligned_substitutive"] = noisy_record(
        "query_aligned_substitutive", retained_target, aligned_noise
    )
    out["query_distant_substitutive"] = noisy_record(
        "query_distant_substitutive", retained_target, distant_noise
    )
    return out


def write_jsonl(path: Path, rows: Iterable[Dict[str, Any]]) -> int:
    path.parent.mkdir(parents=True, exist_ok=True)
    n = 0
    with path.open("w", encoding="utf-8") as f:
        for row in rows:
            f.write(json.dumps(row, ensure_ascii=False) + "\n")
            n += 1
    return n


def build_eval_split(
    encoded_papers: Sequence[EncodedPaper],
    split: str,
    encoder: DenseEncoder,
    pool_docs: Sequence[Document],
    pool_embs: np.ndarray,
    args: argparse.Namespace,
    rng: random.Random,
) -> Dict[str, List[Dict[str, Any]]]:
    buckets = {
        "clean": [],
        "query_aligned_additive": [],
        "query_distant_additive": [],
        "query_aligned_substitutive": [],
        "query_distant_substitutive": [],
    }

    for i, paper in enumerate(encoded_papers, 1):
        conds = build_conditions_for_paper(
            paper=paper,
            encoder=encoder,
            shared_pool_docs=pool_docs,
            shared_pool_embs=pool_embs,
            final_k=args.final_k,
            noise_k=args.noise_k,
            substitutive_clean_k=args.substitutive_clean_k,
            mmr_lambda=args.mmr_lambda,
            rng=rng,
            shuffle_noisy=not args.no_shuffle_noisy,
            split=split,
            single_query=args.single_query,
        )
        for k in buckets:
            row = conds.get(k)
            if row is not None:
                buckets[k].append(row)

        if i % 100 == 0 or i == len(encoded_papers):
            counts = ", ".join(f"{k}={len(v)}" for k, v in buckets.items())
            print(f"[{split}] {i}/{len(encoded_papers)} :: {counts}")

    return buckets


def build_training_rows(
    encoded_papers: Sequence[EncodedPaper],
    encoder: DenseEncoder,
    pool_docs: Sequence[Document],
    pool_embs: np.ndarray,
    args: argparse.Namespace,
    rng: random.Random,
    split: str,
) -> Tuple[List[Dict[str, Any]], List[Dict[str, Any]]]:
    """
    Noise-aware: clean + query-aligned additive + query-distant additive.
    Clean-matched: unique clean controls, matched in row count where possible.

    To avoid repeating identical clean rows, additional unique clean papers should
    be supplied by the caller after the target training slice.
    """
    noiseaware: List[Dict[str, Any]] = []
    clean_rows: List[Dict[str, Any]] = []

    for i, paper in enumerate(encoded_papers, 1):
        conds = build_conditions_for_paper(
            paper=paper,
            encoder=encoder,
            shared_pool_docs=pool_docs,
            shared_pool_embs=pool_embs,
            final_k=args.final_k,
            noise_k=args.noise_k,
            substitutive_clean_k=args.substitutive_clean_k,
            mmr_lambda=args.mmr_lambda,
            rng=rng,
            shuffle_noisy=not args.no_shuffle_noisy,
            split=split,
            single_query=args.single_query,
        )

        if conds.get("clean") is not None:
            clean_rows.append(conds["clean"])
            noiseaware.append(conds["clean"])
        if conds.get("query_aligned_additive") is not None:
            noiseaware.append(conds["query_aligned_additive"])
        if conds.get("query_distant_additive") is not None:
            noiseaware.append(conds["query_distant_additive"])

        if i % 250 == 0 or i == len(encoded_papers):
            print(
                f"[{split}] {i}/{len(encoded_papers)} "
                f"noiseaware={len(noiseaware)} clean_base={len(clean_rows)}"
            )

    return noiseaware, clean_rows


def make_unique_clean_controls(
    candidate_papers: Sequence[EncodedPaper],
    needed: int,
    encoder: DenseEncoder,
    args: argparse.Namespace,
    split: str,
) -> List[Dict[str, Any]]:
    rows: List[Dict[str, Any]] = []
    for paper in candidate_papers:
        if len(rows) >= needed:
            break
        query = choose_query(paper.paper_id, single_query=args.single_query)
        query_emb = encoder.encode(query)[0]
        target = retrieve_target_chunks(
            paper, query_emb, k=args.final_k, mmr_lambda=args.mmr_lambda
        )
        if len(target) < args.final_k:
            continue
        rows.append(
            make_record(
                paper=paper,
                query=query,
                docs=target,
                target_docs=target,
                noise_docs=[],
                split=split,
                condition="clean",
            )
        )
    return rows


def main() -> None:
    args = parse_args()
    out_dir = Path(args.output_dir)
    out_dir.mkdir(parents=True, exist_ok=True)

    random.seed(args.seed)
    np.random.seed(args.seed)
    rng = random.Random(args.seed)

    print("Loading source splits...")
    train_all = filter_target_lengths(
        load_split(args.arxiv_dir, "train"),
        args.min_target_words, args.max_target_words,
    )
    valid_all = filter_target_lengths(
        load_split(args.arxiv_dir, "validation"),
        args.min_target_words, args.max_target_words,
    )
    test_all = filter_target_lengths(
        load_split(args.arxiv_dir, "test"),
        args.min_target_words, args.max_target_words,
    )

    if args.noise_pool_offset < args.train_limit:
        raise ValueError(
            "noise_pool_offset must be >= train_limit so shared distractor-pool "
            "papers do not overlap the target training slice."
        )

    train_targets = train_all[:args.train_limit]
    valid_targets = valid_all[:args.valid_limit]
    test_targets = test_all[:args.test_limit]

    pool_start = args.noise_pool_offset
    pool_stop = pool_start + args.noise_pool_limit
    noise_pool_rows = train_all[pool_start:pool_stop]

    if len(noise_pool_rows) == 0:
        raise RuntimeError("No rows available for the shared training-derived noise pool.")

    print(
        f"train_targets={len(train_targets):,}, "
        f"valid_targets={len(valid_targets):,}, "
        f"test_targets={len(test_targets):,}, "
        f"shared_noise_pool_papers={len(noise_pool_rows):,}"
    )

    encoder = DenseEncoder(
        model_name=args.embedder,
        batch_size=args.encode_batch_size,
        max_length=args.encoder_max_length,
        device=args.device,
    )

    print("\nBuilding ONE shared TRAIN-derived distractor pool...")
    pool_docs, pool_embs = build_shared_noise_pool(noise_pool_rows, encoder)
    print(f"shared pool: {len(pool_docs):,} chunks")

    print("\nEncoding target splits...")
    train_encoded = encode_rows(train_targets, encoder, args.min_chunks, "train")
    valid_encoded = encode_rows(valid_targets, encoder, args.min_chunks, "validation")
    test_encoded = encode_rows(test_targets, encoder, args.min_chunks, "test")

    print("\nBuilding training data...")
    train_noiseaware, train_clean_base = build_training_rows(
        train_encoded, encoder, pool_docs, pool_embs, args, rng, "train"
    )
    valid_noiseaware, valid_clean_base = build_training_rows(
        valid_encoded, encoder, pool_docs, pool_embs, args, rng, "validation"
    )

    # Unique clean controls: first use one clean row from each target paper, then
    # draw additional UNIQUE clean papers from unused source rows.
    train_needed = max(0, len(train_noiseaware) - len(train_clean_base))
    valid_needed = max(0, len(valid_noiseaware) - len(valid_clean_base))

    # Exclude target training slice and shared noise-pool slice.
    extra_train_source = train_all[pool_stop:]
    extra_valid_source = valid_all[args.valid_limit:]

    print(
        f"\nBuilding unique clean controls: "
        f"train_extra_needed={train_needed:,}, valid_extra_needed={valid_needed:,}"
    )

    # Encode only as many extra candidates as reasonably needed, with headroom.
    train_extra_candidates = encode_rows(
        extra_train_source[: max(train_needed * 2, 1)],
        encoder, args.min_chunks, "train_clean_extra"
    ) if train_needed else []

    valid_extra_candidates = encode_rows(
        extra_valid_source[: max(valid_needed * 2, 1)],
        encoder, args.min_chunks, "valid_clean_extra"
    ) if valid_needed else []

    train_clean_extra = make_unique_clean_controls(
        train_extra_candidates, train_needed, encoder, args, "train_clean_extra"
    )
    valid_clean_extra = make_unique_clean_controls(
        valid_extra_candidates, valid_needed, encoder, args, "validation_clean_extra"
    )

    train_clean_matched = train_clean_base + train_clean_extra
    valid_clean_matched = valid_clean_base + valid_clean_extra

    if len(train_clean_matched) < len(train_noiseaware):
        raise RuntimeError(
            f"Not enough unique clean control rows: {len(train_clean_matched)} "
            f"< noise-aware {len(train_noiseaware)}. Increase available train source data."
        )
    if len(valid_clean_matched) < len(valid_noiseaware):
        raise RuntimeError(
            f"Not enough unique validation clean rows: {len(valid_clean_matched)} "
            f"< noise-aware {len(valid_noiseaware)}."
        )

    train_clean_matched = train_clean_matched[:len(train_noiseaware)]
    valid_clean_matched = valid_clean_matched[:len(valid_noiseaware)]

    # Deterministic record-order shuffling.
    rng.shuffle(train_noiseaware)
    rng.shuffle(train_clean_matched)
    rng.shuffle(valid_noiseaware)
    rng.shuffle(valid_clean_matched)

    print("\nBuilding five matched TEST conditions...")
    test_buckets = build_eval_split(
        test_encoded, "test", encoder, pool_docs, pool_embs, args, rng
    )

    # Keep only paper IDs present in ALL five test conditions.
    common_ids = None
    for rows in test_buckets.values():
        ids = {r["paper_id"] for r in rows}
        common_ids = ids if common_ids is None else common_ids & ids
    common_ids = common_ids or set()

    ordered_common = [p.paper_id for p in test_encoded if p.paper_id in common_ids]
    ordered_common = ordered_common[:args.test_limit]
    allowed = set(ordered_common)

    for key in test_buckets:
        test_buckets[key] = [
            r for r in test_buckets[key] if r["paper_id"] in allowed
        ]
        test_buckets[key].sort(key=lambda r: ordered_common.index(r["paper_id"]))

    if len(ordered_common) < args.test_limit:
        print(
            f"[WARN] only {len(ordered_common)} fully matched test papers were built "
            f"out of requested {args.test_limit}."
        )

    print("\nWriting JSONL files...")
    outputs = {
        "train_noiseaware.jsonl": train_noiseaware,
        "train_clean_matched.jsonl": train_clean_matched,
        "valid_noiseaware.jsonl": valid_noiseaware,
        "valid_clean_matched.jsonl": valid_clean_matched,
        "test_clean.jsonl": test_buckets["clean"],
        "test_noisy_easy_additive.jsonl": test_buckets["query_aligned_additive"],
        "test_noisy_hard_additive.jsonl": test_buckets["query_distant_additive"],
        "test_noisy_easy_substitutive.jsonl": test_buckets["query_aligned_substitutive"],
        "test_noisy_hard_substitutive.jsonl": test_buckets["query_distant_substitutive"],
    }

    counts = {}
    for name, rows in outputs.items():
        counts[name] = write_jsonl(out_dir / name, rows)
        print(f"  {name}: {counts[name]:,}")

    manifest = {
        "builder": "databuild_huflit_shared_pool.py",
        "seed": args.seed,
        "embedder": args.embedder,
        "query_templates": QUERY_TEMPLATES,
        "final_k": args.final_k,
        "noise_k": args.noise_k,
        "substitutive_clean_k": args.substitutive_clean_k,
        "mmr_lambda": args.mmr_lambda,
        "shared_noise_pool": {
            "source_split": "train",
            "offset": args.noise_pool_offset,
            "paper_limit": args.noise_pool_limit,
            "num_chunks": len(pool_docs),
            "reused_for": ["train", "validation", "test"],
        },
        "similarity_bands": {
            "query_aligned": {
                "primary_percentile_band": [QUERY_ALIGNED_LOW, QUERY_ALIGNED_HIGH],
                "fallback_percentile_band": [
                    QUERY_ALIGNED_FALLBACK_LOW,
                    QUERY_ALIGNED_FALLBACK_HIGH,
                ],
            },
            "query_distant": {
                "primary_bottom_percentile": QUERY_DISTANT_MAX,
                "fallback_bottom_percentile": QUERY_DISTANT_FALLBACK_MAX,
            },
        },
        "shuffle_noisy": not args.no_shuffle_noisy,
        "output_counts": counts,
        "post_truncation_token_provenance": False,
        "chunk_level_context_provenance_saved": True,
        "note": (
            "context_segments preserves target/noise chunk provenance before model-specific "
            "tokenization. Direct post-truncation NER/TRR still requires instrumentation in "
            "the model tokenizer/evaluation stage."
        ),
    }
    (out_dir / "dataset_build_manifest.json").write_text(
        json.dumps(manifest, indent=2, ensure_ascii=False),
        encoding="utf-8",
    )

    print("\nDONE")
    print(f"Output: {out_dir.resolve()}")
    print(
        "Shared distractor pool is TRAIN-derived and reused across "
        "train / validation / test noisy construction."
    )


if __name__ == "__main__":
    main()
